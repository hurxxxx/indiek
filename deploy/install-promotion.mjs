import {mkdirSync,copyFileSync} from 'node:fs';
import {homedir} from 'node:os';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const root=fileURLToPath(new URL('../',import.meta.url));
if(process.platform!=='linux'||root.replace(/\/$/,'')!==path.join(homedir(),'projects/indiek'))throw new Error('Run from ~/projects/indiek on the Linux promotion server.');
const units=path.join(homedir(),'.config/systemd/user');
for(const dir of [units,path.join(root,'promotion/state'),path.join(homedir(),'.config/indiek-promotion')])mkdirSync(dir,{recursive:true,mode:0o700});
for(const name of ['prepare','threads','instagram','weekly'])for(const extension of ['service','timer'])copyFileSync(path.join(root,`deploy/systemd/indiek-promotion-${name}.${extension}`),path.join(units,`indiek-promotion-${name}.${extension}`));
execFileSync('systemctl',['--user','daemon-reload'],{stdio:'inherit'});
execFileSync('systemctl',['--user','enable','--now',...['prepare','threads','instagram','weekly'].map(name=>`indiek-promotion-${name}.timer`)],{stdio:'inherit'});
console.log('Timers installed. Publishing still requires valid account authorization and public source/media.');
